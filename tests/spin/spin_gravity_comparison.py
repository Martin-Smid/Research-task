def analyse(folder, sim, spin, n_grid):
    """Read the saved snapshots of one run and return the time series (dict of arrays)."""
    files = sorted(glob.glob(os.path.join(folder, "wf_0_snapshot_at_time_*.npy")),
                   key=lambda f: float(os.path.basename(f).split("time_")[1][:-4]))
    n_comp = int(round(2 * spin + 1))
    dV = (2 * BOX / n_grid) ** 3
    dx = 2 * BOX / n_grid
    out = {key: [] for key in ("time", "variance", "rho_max", "mass", "mass_fractions", "spin_total", "spin_sq", "phase")}
    for path in files:
        fields = [np.load(path.replace("wf_0_", f"wf_{m}_")) for m in range(n_comp)]
        rho = sum(np.abs(f) ** 2 for f in fields)
        mean = rho.mean()
        out["time"].append(float(os.path.basename(path).split("time_")[1][:-4]))
        out["variance"].append(np.var(rho / mean))
        out["rho_max"].append(rho.max() / mean)
        out["mass"].append(rho.sum() * dV)
        out["mass_fractions"].append([np.sum(np.abs(f) ** 2) / rho.sum() for f in fields])
        out["phase"].append(potential_phase(rho, BOX, float(sim.G), H, float(sim.h_bar_tilde)))
        if float(spin).is_integer() and spin >= 1:
            S = spin_density(fields, spin)
            out["spin_total"].append([s.sum() * dV for s in S])
            out["spin_sq"].append(np.mean(S[0] ** 2 + S[1] ** 2 + S[2] ** 2) / mean ** 2)
        else:
            out["spin_total"].append([0.0, 0.0, 0.0])
            out["spin_sq"].append(0.0)
        if path is files[0]:
            out["k"], out["P_start"] = power_spectrum(rho / mean - 1)
        if path is files[-1]:
            _, out["P_end"] = power_spectrum(rho / mean - 1)
            out["core_rho"], out["core_r_half"] = core_properties(rho, dx)
            out["core_rho_over_mean"] = out["core_rho"] / mean
    result = {key: np.array(value) for key, value in out.items()}
    energy = np.genfromtxt(os.path.join(folder, "energy.csv"), delimiter=",", names=True)
    result["energy_time"], result["energy"] = energy["time"], energy["E_total"]
    result["energy_K"], result["energy_W"] = energy["K_total"], energy["W"]
    return result


