def load_cases(spin, n_grid):
    cases = []
    for seed in SEEDS:
        path = case_path(spin, n_grid, seed)
        if os.path.exists(path):
            with np.load(path) as data:
                cases.append({key: data[key] for key in data.files})
    return cases


def per_case_numbers(case):
    spin = float(case["spin"])
    n = int(round(2 * spin + 1))
    has_spin = spin.is_integer() and spin >= 1
    last = np.searchsorted(case["time"], COMPARE_TIME + 1e-9) - 1 if COMPARE_TIME > 0 else -1
    drift = lambda a: np.max(np.abs(a - a[0])) / np.abs(a[0])
    spin_total = case["spin_total"]
    spin_scale = np.sum(case["mass"][0])                         # mass = number of bosons * m, spin per boson is in units of hbar
    core_clear = case["core_rho_over_mean"] > CORE_FACTOR and case["core_r_half"] > 1.5 * 2 * BOX / int(case["n_grid"])
    return {
        "variance*n (t=0)": case["variance"][0] * n,
        "variance (end)": case["variance"][last],
        "rho_max/mean (end)": case["rho_max"][last],
        **{f"t(rho_max/mean>{th:g}) [Gyr]": collapse_time(case["time"], case["rho_max"], th) for th in COLLAPSE_THRESHOLDS},
        "mass drift": drift(case["mass"]),
        "energy drift": drift(case["energy"]),
        "fraction drift": np.max(np.abs(case["mass_fractions"] - case["mass_fractions"][0])),
        "spin drift /M": np.max(np.abs(spin_total - spin_total[0])) / spin_scale if has_spin else np.nan,
        "spin |S|^2/rho^2 (end/start)": case["spin_sq"][-1] / case["spin_sq"][0] if has_spin else np.nan,
        "max phase/step": np.max(case["phase"]),
        "core rho/mean": case["core_rho_over_mean"] if core_clear else np.nan,
        "core r_half [kpc]": case["core_r_half"] if core_clear else np.nan,
    }


def table(spins, n_grid, label):
    rows = {}
    for spin in spins:
        cases = load_cases(spin, n_grid)
        if not cases:
            continue
        numbers = [per_case_numbers(c) for c in cases]
        rows[spin] = {key: np.array([n[key] for n in numbers]) for key in numbers[0]}
    if not rows:
        return {}
    print(f"\n{label}: N = {n_grid}, mean +- scatter (std over seeds); n seeds in brackets; nan = not applicable / not reached")
    keys = list(next(iter(rows.values())).keys())
    print(f"{'quantity':32s}" + "".join(f"  s={s} (n={2 * s + 1}, {len(rows[s][keys[0]])} seeds)".rjust(30) for s in rows))
    for key in keys:
        cells = []
        for s in rows:
            v = rows[s][key]
            good = v[np.isfinite(v)]
            cells.append(f"{good.mean():.3e} +- {good.std(ddof=1) if len(good) > 1 else float('nan'):.1e} [{len(good)}]".rjust(30) if len(good) else "-".rjust(30))
        print(f"{key:32s}" + "".join(cells))
    return rows


def plot_main(spins, n_grid):
    colors = {0: "tab:blue", 1: "tab:orange", 2: "tab:green"}
    fig, axes = plt.subplots(1, 3, figsize=(16, 4.5))
    for spin in spins:
        cases = load_cases(spin, n_grid)
        if not cases:
            continue
        t = cases[0]["time"]
        label = f"s={spin} (n={2 * spin + 1})"
        for ax, key in ((axes[0], "variance"), (axes[1], "rho_max")):
            values = np.array([c[key] for c in cases])
            ax.plot(t, values.mean(0), color=colors.get(spin, "tab:gray"), label=label)
            ax.fill_between(t, values.mean(0) - values.std(0, ddof=1), values.mean(0) + values.std(0, ddof=1), color=colors.get(spin, "tab:gray"), alpha=0.25)
        k = cases[0]["k"]
        P = np.array([c["P_end"] for c in cases])
        axes[2].loglog(k, P.mean(0), color=colors.get(spin, "tab:gray"), label=label)
        axes[2].fill_between(k, np.maximum(P.mean(0) - P.std(0, ddof=1), 1e-300), P.mean(0) + P.std(0, ddof=1), color=colors.get(spin, "tab:gray"), alpha=0.25)
    axes[0].set(xlabel="t [Gyr]", ylabel="variance of rho / rho_mean", yscale="log")
    axes[1].set(xlabel="t [Gyr]", ylabel="rho_max / rho_mean", yscale="log")
    axes[2].set(xlabel="k [fundamental modes]", ylabel="P_rho(k) of delta (t = end)")
    for ax in axes:
        ax.legend()
        ax.grid(alpha=0.3)
    fig.suptitle(f"Self-gravitating field, N = {n_grid}, mean and scatter over seeds")
    fig.tight_layout()
    fig.savefig(os.path.join(OUTPUT_DIR, "spin_gravity_comparison.png"), dpi=130)


def convergence():
    cases_by_n = {n: load_cases(CONV_SPIN, n) for n in CONV_NS}
    cases_by_n = {n: c for n, c in cases_by_n.items() if c}
    if len(cases_by_n) < 2:
        return
    finest = max(cases_by_n)
    print(f"\nConvergence, spin {CONV_SPIN}: the same physical fields at N = {sorted(cases_by_n)}, seeds {SEEDS}")
    print("paired differences w.r.t. N =", finest, "(mean over seeds of |x_N - x_fine| / |x_fine|), and the seed scatter of x_fine")
    for key in ("variance (end)", "rho_max/mean (end)", f"t(rho_max/mean>{COLLAPSE_THRESHOLDS[0]:g}) [Gyr]"):
        fine = {int(c["seed"]): per_case_numbers(c)[key] for c in cases_by_n[finest]}
        scatter = np.nanstd(list(fine.values()), ddof=1) / np.nanmean(list(fine.values()))
        parts = []
        for n in sorted(cases_by_n):
            if n == finest:
                continue
            diffs = [abs(per_case_numbers(c)[key] - fine[int(c["seed"])]) / abs(fine[int(c["seed"])]) for c in cases_by_n[n] if int(c["seed"]) in fine]
            parts.append(f"N={n}: {np.nanmean(diffs):.2e}")
        print(f"  {key:22s} {', '.join(parts)};  relative seed scatter at N={finest}: {scatter:.2e}")
    fig, axes = plt.subplots(1, 3, figsize=(16, 4.5))
    for n, cases in sorted(cases_by_n.items()):
        t = cases[0]["time"]
        for ax, key in ((axes[0], "variance"), (axes[1], "rho_max")):
            ax.plot(t, np.mean([c[key] for c in cases], axis=0), label=f"N={n}")
        axes[2].loglog(cases[0]["k"], np.mean([c["P_end"] for c in cases], axis=0), label=f"N={n}")
    axes[0].set(xlabel="t [Gyr]", ylabel="variance of rho / rho_mean", yscale="log")
    axes[1].set(xlabel="t [Gyr]", ylabel="rho_max / rho_mean", yscale="log")
    axes[2].set(xlabel="k [fundamental modes]", ylabel="P_rho(k) (t = end)")
    for ax in axes:
        ax.legend()
        ax.grid(alpha=0.3)
    fig.suptitle(f"Resolution study, spin {CONV_SPIN}, seed-averaged")
    fig.tight_layout()
    fig.savefig(os.path.join(OUTPUT_DIR, "convergence.png"), dpi=130)


def report():
    kinetic_limit = 0.5 * 4 / (3 * np.pi) * (2 * BOX / N) ** 2 / 7.842780153469577
    print(f"\nh = {H} Gyr, kinetic stability limit (0.5 x criterion) at N = {N}: {kinetic_limit:.3e} Gyr, "
          f"at N = {max(CONV_NS)}: {0.5 * 4 / (3 * np.pi) * (2 * BOX / max(CONV_NS)) ** 2 / 7.842780153469577:.3e} Gyr")
    table(SPINS, N, "Main comparison")
    plot_main(SPINS, N)
    convergence()
    print(f"\nResults and plots in: {OUTPUT_DIR}")


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "main"
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    if mode == "main":
        for seed in SEEDS:
            for spin in SPINS:
                run_case(spin, N, seed)
    elif mode == "conv":
        for seed in SEEDS:
            for n_grid in CONV_NS:
                run_case(CONV_SPIN, n_grid, seed)
    report()


if __name__ == "__main__":
    main()
