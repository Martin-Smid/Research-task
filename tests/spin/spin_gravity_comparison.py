def case_path(spin, n_grid, seed):
    return os.path.join(OUTPUT_DIR, f"case_s{spin}_N{n_grid}_seed{seed}.npz")


def run_case(spin, n_grid, seed):
    path = case_path(spin, n_grid, seed)
    if os.path.exists(path):
        print(f"skip s={spin} N={n_grid} seed={seed} (done)")
        return
    start = time.time()
    fields = initial_fields(spin, seed, n_grid)
    with redirect_stdout(io.StringIO()):
        sim, _ = build_sim(spin, n_grid)
        sim.initialize_simulation()
        for wave, field in zip(sim.wave_functions, fields):
            wave.psi = cp.asarray(field, dtype=cp.complex128)
        if SIM_DIR:
            os.makedirs(SIM_DIR, exist_ok=True)
            sim.evolution.scribe.output_root = SIM_DIR
        sim.evolution.evolve(sim.wave_functions, save_every=SAVE_EVERY, diagnostics_every=SAVE_EVERY)
    folder = sim.evolution.scribe.snapshot_directory
    with open(os.path.join(OUTPUT_DIR, "run_folders.txt"), "a") as handle:
        handle.write(f"{folder}\ts={spin} N={n_grid} seed={seed}\n")
    result = analyse(folder, sim, spin, n_grid)
    np.savez(path, spin=spin, n_grid=n_grid, seed=seed, **result)
    cp.get_default_memory_pool().free_all_blocks()
    print(f"done s={spin} N={n_grid} seed={seed}: variance {result['variance'][0]:.3f} -> {result['variance'][-1]:.3f}, "
          f"rho_max/mean {result['rho_max'][-1]:.1f}, {time.time() - start:.0f} s")


