"""Measurement: how does the number of independent polarizations n = 2s+1 change the self-gravitating ULDM density field?

Scalar (s = 0, n = 1), vector (s = 1, n = 3) and spin-2 (n = 5) fields in the same periodic box, with the same total mass and
the same power spectrum per component, evolved with gravity on. Every polarization is an independent Gaussian random field
(Wave_vector_class(independent_fields=True, power_spectrum=...), equal mass fractions); s = 0 uses the same generator.

Initial power spectrum: flat for |k| <= K_MAX fundamental modes, zero above. The cut keeps the field smooth on the scales that
the grid resolves with many points per de Broglie wavelength (K_MAX = 8: 16 cells per wavelength at N = 64), and puts the
excitation at or just above the quantum Jeans wave number, so that the density contrast delta = rho/rho_mean - 1 starts at
variance 1/n and then collapses gravitationally; modes above the cut are generated by the evolution itself.

Resolution study: the fields of one seed are generated ONCE at N_FINE with the code's generator and cut in Fourier space to the
requested N (exact, because K_MAX << N/2), so all N evolve the same physical field. The total mass is rescaled to
RHO_MEAN * volume (a common factor for all components, the mass fractions are untouched).

Measured at every saved time, for every case: variance of rho/rho_mean, rho_max/rho_mean, total and per-component mass, total
energy (energy.csv), for s >= 1 the spin density S_k = sum psi_m^* (J_k)_{mm'} psi_m' (J in the m basis of Wave_vector_class,
m = -s ... s) and the maximum phase per step |Phi|_max h / h_bar_tilde; at t = 0 and at the end the angular-averaged power
spectrum P_rho(k) and, if a core is clearly present, its central density and half-density radius. The collapse time is the first
time at which rho_max / rho_mean first exceeds a threshold of COLLAPSE_THRESHOLDS (linear interpolation between the saved times).

Usage (repository root, project venv; the runs are sequential):
    python tests/spin/spin_gravity_comparison.py main      # spins SPINS x SEEDS at N
    python tests/spin/spin_gravity_comparison.py conv      # spin CONV_SPIN x SEEDS at the N in CONV_NS (cases already done are skipped)
    python tests/spin/spin_gravity_comparison.py report    # table and plots from the saved cases
Constants can be overridden by environment variables of the same name (e.g. RHO_MEAN=2e6 SEEDS=1,2); FRACTIONS=0.8,0.1,0.1 sets unequal mass fractions of the polarizations. Output (not in the
repository): resources/data/spin_gravity_comparison<TAG>/ holds one .npz per case, the table, the plots and run_folders.txt, the
list of the simulation_* folders created by the runs (they hold the snapshots and are NOT deleted by this script)."""

